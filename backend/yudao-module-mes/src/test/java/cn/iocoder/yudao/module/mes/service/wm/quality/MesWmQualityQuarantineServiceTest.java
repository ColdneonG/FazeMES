package cn.iocoder.yudao.module.mes.service.wm.quality;

import cn.iocoder.yudao.framework.common.exception.ServiceException;
import cn.iocoder.yudao.framework.tenant.core.context.TenantContextHolder;
import org.junit.jupiter.api.*;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.*;
import org.springframework.test.util.ReflectionTestUtils;
import org.springframework.transaction.support.TransactionTemplate;

import java.util.*;
import java.util.concurrent.*;

import static org.junit.jupiter.api.Assertions.*;

/** Real H2 configuration creation, tenant boundaries, rollback and simultaneous initialization. */
class MesWmQualityQuarantineServiceTest {
    private JdbcTemplate jdbc;
    private MesWmQualityQuarantineService service;
    private TransactionTemplate transaction;

    @BeforeEach void fixture() {
        var source = new DriverManagerDataSource("jdbc:h2:mem:quality_config_" + UUID.randomUUID()
                + ";MODE=MySQL;DB_CLOSE_DELAY=-1;LOCK_TIMEOUT=10000", "sa", "");
        jdbc = new JdbcTemplate(source);
        transaction = new TransactionTemplate(new DataSourceTransactionManager(source));
        jdbc.execute("CREATE TABLE mes_wm_quality_config_lock(tenant_id BIGINT PRIMARY KEY)");
        jdbc.execute("CREATE TABLE mes_wm_stock_quality_hold(id BIGINT PRIMARY KEY,tenant_id BIGINT,material_stock_id BIGINT,source_transaction_id BIGINT,source_biz_type INT,source_biz_id BIGINT,source_biz_line_id BIGINT,arrival_transaction_id BIGINT,observed_quantity DECIMAL(20,6),reason VARCHAR(500),status VARCHAR(40),create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
        String base = ",remark VARCHAR(500),creator VARCHAR(64),updater VARCHAR(64),deleted BOOLEAN DEFAULT FALSE,tenant_id BIGINT NOT NULL";
        jdbc.execute("CREATE TABLE mes_wm_warehouse(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,code VARCHAR(128),name VARCHAR(255),frozen BOOLEAN" + base + ")");
        jdbc.execute("CREATE TABLE mes_wm_warehouse_location(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,code VARCHAR(128),name VARCHAR(255),warehouse_id BIGINT,frozen BOOLEAN" + base + ")");
        jdbc.execute("CREATE TABLE mes_wm_warehouse_area(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,code VARCHAR(128),name VARCHAR(255),location_id BIGINT,status INT,frozen BOOLEAN,allow_item_mixing BOOLEAN,allow_batch_mixing BOOLEAN" + base + ")");
        service = new MesWmQualityQuarantineService();
        ReflectionTestUtils.setField(service, "jdbc", jdbc);
        TenantContextHolder.setTenantId(1L);
    }
    @AfterEach void clear() { TenantContextHolder.clear(); }

    @Test void emptyNewTenantCanInitializeConfigurationWithoutCreatingBusinessData() {
        var created = initialize();
        assertEquals(created, initialize());
        for (String table : List.of("mes_wm_warehouse", "mes_wm_warehouse_location", "mes_wm_warehouse_area")) {
            assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM " + table, Integer.class));
        }
        assertEquals(created.get("warehouseId"), jdbc.queryForObject("SELECT warehouse_id FROM mes_wm_warehouse_location", Long.class));
        assertEquals(created.get("locationId"), jdbc.queryForObject("SELECT location_id FROM mes_wm_warehouse_area", Long.class));
        assertEquals(0, jdbc.queryForObject("SELECT status FROM mes_wm_warehouse_area", Integer.class));
        assertFalse(jdbc.queryForObject("SELECT frozen FROM mes_wm_warehouse", Boolean.class));
    }

    @Test void configurationsAreIndependentAcrossTenants() {
        var first = initialize();
        TenantContextHolder.setTenantId(2L);
        var second = initialize();
        assertNotEquals(first.get("warehouseId"), second.get("warehouseId"));
        assertEquals(2, jdbc.queryForObject("SELECT COUNT(*) FROM mes_wm_warehouse", Integer.class));
    }

    @Test void missingTenantCannotCreateAnyConfiguration() {
        TenantContextHolder.clear();
        assertThrows(RuntimeException.class, this::initialize);
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM mes_wm_warehouse", Integer.class));
    }

    @Test void identityOrParentConflictRollsBackEverythingCreatedDuringInitialization() {
        jdbc.update("INSERT INTO mes_wm_warehouse_location(code,warehouse_id,remark,tenant_id) VALUES(?,999,'SYSTEM_QUALITY_QUARANTINE',1)", MesWmQualityPolicy.QUARANTINE_LOCATION);
        assertThrows(ServiceException.class, this::initialize);
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM mes_wm_warehouse", Integer.class));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM mes_wm_warehouse_area", Integer.class));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM mes_wm_quality_config_lock", Integer.class));
    }

    @Test void existingOrdinaryWarehouseCannotBeSilentlyReinterpretedAsQuarantine() {
        jdbc.update("INSERT INTO mes_wm_warehouse(code,name,remark,tenant_id) VALUES(?,'旧普通仓','ordinary',1)", MesWmQualityPolicy.QUARANTINE_WAREHOUSE);
        assertThrows(ServiceException.class, this::initialize);
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM mes_wm_warehouse_location", Integer.class));
    }

    @Test void deletedReservedIdentityIsNotRecreatedAndNullFrozenConfigurationIsRejected() {
        initialize();
        jdbc.update("UPDATE mes_wm_warehouse SET deleted=TRUE");
        assertThrows(ServiceException.class, this::initialize);
        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM mes_wm_warehouse", Integer.class));
        jdbc.update("UPDATE mes_wm_warehouse SET deleted=FALSE,frozen=NULL");
        assertThrows(ServiceException.class, this::initialize);
    }

    @Test void historicalEvidencePageIncludesUnresolvedRowsButNeverAnotherTenantsEvidence() {
        jdbc.update("INSERT INTO mes_wm_stock_quality_hold VALUES(1,1,10,101,119,20,30,101,100,'混合待核对','PENDING_REVIEW',CURRENT_TIMESTAMP)");
        jdbc.update("INSERT INTO mes_wm_stock_quality_hold VALUES(2,1,NULL,102,119,21,31,102,NULL,'无法定位待核对','PENDING_REVIEW',CURRENT_TIMESTAMP)");
        jdbc.update("INSERT INTO mes_wm_stock_quality_hold VALUES(3,2,10,103,119,22,32,103,200,'其他租户','PENDING_REVIEW',CURRENT_TIMESTAMP)");
        var page = service.history(new cn.iocoder.yudao.module.mes.controller.admin.wm.materialstock.vo.MesWmQualityHoldPageReqVO());
        assertEquals(2, page.getTotal());
        assertNull(page.getList().get(0).getMaterialStockId());
        assertEquals(102L, page.getList().get(0).getSourceTransactionId());
        assertEquals("无法定位待核对", page.getList().get(0).getReason());
        var filtered = service.history(new cn.iocoder.yudao.module.mes.controller.admin.wm.materialstock.vo.MesWmQualityHoldPageReqVO().setMaterialStockId(10L));
        assertEquals(1, filtered.getTotal());
        assertEquals(101L, filtered.getList().get(0).getArrivalTransactionId());
    }

    @Test void concurrentInitializersShareTheTenantDatabaseLockAndReturnTheSameIds() throws Exception {
        ExecutorService executor = Executors.newFixedThreadPool(2);
        try {
            CountDownLatch start = new CountDownLatch(1);
            Callable<Map<String, Long>> create = () -> {
                TenantContextHolder.setTenantId(1L);
                try { start.await(); return initialize(); }
                finally { TenantContextHolder.clear(); }
            };
            var first = executor.submit(create);
            var second = executor.submit(create);
            start.countDown();
            assertEquals(first.get(10, TimeUnit.SECONDS), second.get(10, TimeUnit.SECONDS));
            assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM mes_wm_warehouse", Integer.class));
        } finally { executor.shutdownNow(); }
    }

    private Map<String, Long> initialize() { return transaction.execute(status -> service.initialize()); }
}
