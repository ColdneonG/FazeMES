    @Test void actualBrokyElevenProcessesFreezeOnlyTheirDeclaredAdjacentSources() throws Exception {
        com.fasterxml.jackson.databind.JsonNode master;
        try (var input=getClass().getResourceAsStream("/sql/broky_flow_master.json")) {
            assertNotNull(input);master=new com.fasterxml.jackson.databind.ObjectMapper().readTree(input).get("tables");
        }
        for (String table:List.of("mes_pro_feedback_ancestor","mes_pro_feedback_source","mes_pro_feedback","mes_pro_task","mes_pro_route_process","mes_pro_process","mes_pro_work_order")) jdbc.update("DELETE FROM "+table);
        for(var process:master.get("mes_pro_process")) jdbc.update("INSERT INTO mes_pro_process VALUES(?,?,1,0)",process.get("id").asLong(),process.get("name").asText());
        for(var step:master.get("mes_pro_route_process")) jdbc.update("INSERT INTO mes_pro_route_process VALUES(?,?,?,?,1,0)",step.get("id").asLong(),step.get("route_id").asLong(),step.get("process_id").asLong(),step.get("sort").asInt());
        int reports=0;
        for(var product:master.get("mes_pro_route_product")) {
            long route=product.get("route_id").asLong(),item=product.get("item_id").asLong(),order=10_000_000+item;
            jdbc.update("INSERT INTO mes_pro_work_order VALUES(?,1,0)",order);
            var steps=new ArrayList<com.fasterxml.jackson.databind.JsonNode>();
            master.get("mes_pro_route_process").forEach(step->{if(step.get("route_id").asLong()==route)steps.add(step);});
            steps.sort(Comparator.comparingInt(step->step.get("sort").asInt()));Long prior=null;
            for(var step:steps) {
                long process=step.get("process_id").asLong(),report=process;
                jdbc.update("INSERT INTO mes_pro_task VALUES(?,?,?,?,?,1,0)",report,order,route,process,item);
                jdbc.update("INSERT INTO mes_pro_feedback(id,code,work_order_id,task_id,route_id,process_id,item_id,feedback_quantity,qualified_quantity,status,tenant_id) VALUES(?,?,?,?,?,?,?,1,1,0,1)",report,"BROKY-FLOW-"+report,order,report,route,process,item);
                if(prior!=null) { assertThrows(ServiceException.class,()->service.validateForSubmission(feedback(report))); }
                service.saveDraft(feedback(report),prior==null?List.of():List.of(source(prior,"1.000000")));
                service.validateForSubmission(feedback(report));approving(report);service.freeze(feedback(report));
                jdbc.update("UPDATE mes_pro_feedback SET status=4 WHERE id=?",report);
                assertTrue(service.context(report,report).isComplete());prior=report;reports++;
            }
        }
        assertEquals(11,reports);assertEquals(11,jdbc.queryForObject("SELECT COUNT(*) FROM mes_pro_feedback WHERE flow_required=1 AND flow_complete=1",Integer.class));
        assertEquals(8,jdbc.queryForObject("SELECT COUNT(*) FROM mes_pro_feedback_source WHERE frozen=1",Integer.class));
        assertEquals(16,jdbc.queryForObject("SELECT COUNT(*) FROM mes_pro_feedback_ancestor",Integer.class));
    }

    @Test void allocationCommittedWhileApprovalWaitsIsReadFromCurrentState() throws Exception {
        service.saveDraft(feedback(201),List.of(source(101,"0.9")));service.saveDraft(feedback(202),List.of(source(101,"0.4")));approving(201);approving(202);
        CountDownLatch locked=new CountDownLatch(1),commit=new CountDownLatch(1),started=new CountDownLatch(1);ExecutorService workers=Executors.newFixedThreadPool(2);
        try {
            Future<?> writer=workers.submit(()->{authenticate();try{new TransactionTemplate(transactions).executeWithoutResult(tx->{jdbc.queryForObject("SELECT id FROM mes_pro_work_order WHERE id=1 FOR UPDATE",Long.class);service.freeze(feedback(201));jdbc.update("UPDATE mes_pro_feedback SET status=3 WHERE id=201");locked.countDown();try{if(!commit.await(10,TimeUnit.SECONDS))throw new IllegalStateException("timeout");}catch(InterruptedException e){throw new RuntimeException(e);}});}finally{clear();}});
            assertTrue(locked.await(10,TimeUnit.SECONDS));
            Future<?> reader=workers.submit(()->{authenticate();try{TransactionTemplate rr=new TransactionTemplate(transactions);// H2 retains its old RR snapshot even for locking reads; InnoDB RR is exercised by the opt-in native wrapper.
            rr.setIsolationLevel(jdbc.getDataSource() instanceof JdbcDataSource ? TransactionDefinition.ISOLATION_READ_COMMITTED : TransactionDefinition.ISOLATION_REPEATABLE_READ);started.countDown();assertThrows(ServiceException.class,()->rr.executeWithoutResult(tx->service.freeze(feedback(202))));}finally{clear();}});
            assertTrue(started.await(5,TimeUnit.SECONDS));assertThrows(TimeoutException.class,()->reader.get(150,TimeUnit.MILLISECONDS));commit.countDown();writer.get(10,TimeUnit.SECONDS);reader.get(10,TimeUnit.SECONDS);
            assertEquals(1,jdbc.queryForObject("SELECT COUNT(*) FROM mes_pro_feedback_source WHERE frozen=1",Integer.class));
        } finally {commit.countDown();workers.shutdownNow();}
    }
