    MesProFeedbackDO feedback(long id){var row=jdbc.queryForMap("SELECT * FROM mes_pro_feedback WHERE id=?",id);return new MesProFeedbackDO().setId(id).setTaskId(((Number)row.get("task_id")).longValue()).setWorkOrderId(((Number)row.get("work_order_id")).longValue()).setFeedbackQuantity((BigDecimal)row.get("feedback_quantity"));}
