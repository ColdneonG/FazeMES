/** Actual shared transaction service, stock service and MyBatis SQL, isolated in-memory H2. */
@Import({MesWmTransactionServiceImpl.class, MesWmMaterialStockServiceImpl.class,
        MesWmQualityQuarantineTransactionTest.Transactions.class})
class MesWmQualityQuarantineTransactionTest extends BaseDbUnitTest {
    @org.springframework.test.context.bean.override.mockito.MockitoBean
    private cn.iocoder.yudao.module.mes.service.wm.returnsales.MesWmReturnSalesSourceService returnSourceService;
    @Configuration(proxyBeanMethods = false)
    @EnableTransactionManagement(proxyTargetClass = true)
    static class Transactions {
        @Bean JdbcTemplate jdbcTemplate(javax.sql.DataSource source) { return new JdbcTemplate(source); }
    }
    @Resource private MesWmTransactionService transactions;
    @Resource private MesWmMaterialStockService stocks;
    @Resource private MesWmMaterialStockMapper stockMapper;
    @Resource private JdbcTemplate jdbc;
    @Resource private cn.iocoder.yudao.module.mes.dal.mysql.pro.kitting.MesProKittingMapper kittingMapper;
    @MockitoBean private MesMdItemService itemService;
    @MockitoBean private MesMdItemTypeService itemTypeService;
    @MockitoBean private MesWmBatchService batchService;
    @MockitoBean private MesWmWarehouseService warehouseService;
    @MockitoBean private MesWmWarehouseLocationService locationService;
    @MockitoBean private MesWmWarehouseAreaService areaService;
    @MockitoBean private MesProKittingService kittingService;
    @MockitoBean private cn.iocoder.yudao.module.mes.service.cost.MesCostService costService;

    @BeforeEach void fixture() {
        String base = ",creator VARCHAR(64) DEFAULT '',create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,updater VARCHAR(64) DEFAULT '',update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,deleted BOOLEAN DEFAULT FALSE,tenant_id BIGINT DEFAULT 0";
        jdbc.execute("CREATE TABLE IF NOT EXISTS mes_wm_warehouse_area(id BIGINT PRIMARY KEY,location_id BIGINT,code VARCHAR(128),name VARCHAR(255),status INT DEFAULT 0,frozen BOOLEAN DEFAULT FALSE,allow_item_mixing BOOLEAN DEFAULT TRUE,allow_batch_mixing BOOLEAN DEFAULT TRUE" + base + ")");
        jdbc.execute("CREATE TABLE IF NOT EXISTS mes_wm_transaction(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,type INT,biz_type INT,biz_id BIGINT,biz_code VARCHAR(128),biz_line_id BIGINT,material_stock_id BIGINT,work_order_id BIGINT,related_transaction_id BIGINT,item_id BIGINT,quantity DECIMAL(20,6),batch_id BIGINT,batch_code VARCHAR(128),warehouse_id BIGINT,location_id BIGINT,area_id BIGINT,transaction_time TIMESTAMP,erp_time TIMESTAMP,receipt_time TIMESTAMP" + base + ")");
        jdbc.execute("CREATE TABLE IF NOT EXISTS mes_wm_warehouse(id BIGINT PRIMARY KEY,code VARCHAR(128),name VARCHAR(255),frozen BOOLEAN DEFAULT FALSE" + base + ")");
        jdbc.execute("CREATE TABLE IF NOT EXISTS mes_wm_warehouse_location(id BIGINT PRIMARY KEY,warehouse_id BIGINT,name VARCHAR(255),frozen BOOLEAN DEFAULT FALSE" + base + ")");
        jdbc.update("DELETE FROM mes_wm_warehouse_area");
        jdbc.update("DELETE FROM mes_wm_transaction");
        jdbc.update("DELETE FROM mes_wm_warehouse");
        jdbc.update("DELETE FROM mes_wm_warehouse_location");
        jdbc.update("INSERT INTO mes_wm_warehouse(id,code) VALUES(2,'FG'),(20,'QUALITY_QUARANTINE_WAREHOUSE')");
        jdbc.update("INSERT INTO mes_wm_warehouse_location(id,warehouse_id) VALUES(3,2),(30,20)");
        jdbc.update("INSERT INTO mes_wm_warehouse_area(id,location_id) VALUES(4,3),(40,30)");
        when(itemService.validateItemExists(7L)).thenReturn(new MesMdItemDO().setId(7L).setBatchFlag(false).setItemTypeId(1L));
        when(warehouseService.validateWarehouseExists(anyLong())).thenAnswer(i ->
                new MesWmWarehouseDO().setId(i.getArgument(0)).setCode(Long.valueOf(20L).equals(i.getArgument(0))
                        ? MesWmQualityPolicy.QUARANTINE_WAREHOUSE : "FG").setFrozen(false));
        when(warehouseService.getWarehouseByCode(MesWmQualityPolicy.QUARANTINE_WAREHOUSE))
                .thenReturn(new MesWmWarehouseDO().setId(20L).setCode(MesWmQualityPolicy.QUARANTINE_WAREHOUSE));
        when(locationService.validateWarehouseLocationExists(anyLong())).thenAnswer(i ->
                new MesWmWarehouseLocationDO().setId(i.getArgument(0)).setFrozen(false));
        when(areaService.validateWarehouseAreaExists(anyLong())).thenAnswer(i ->
                new MesWmWarehouseAreaDO().setId(i.getArgument(0)).setFrozen(false).setAllowItemMixing(true).setAllowBatchMixing(true));
    }

    @Test void isolatedInboundCreatesIndependentStockFromSameBatchGoodStock() {
        var good = stock(2, 3, 4, false, false);
        transactions.createTransaction(request(1, 119, 20, 30, 40).setMaterialStockId(null));
        assertQuantity(good.getId(), "100");
        var isolated = stockMapper.selectList().stream().filter(s -> s.getWarehouseId() == 20).findFirst().orElseThrow();
        assertNotEquals(good.getId(), isolated.getId());
        assertQuantity(isolated.getId(), "5");
        assertFalse(Boolean.TRUE.equals(isolated.getFrozen()));
        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM mes_wm_transaction", Integer.class));
    }

    @Test void salesIssueTransferAndMiscellaneousCannotRemoveQuarantinedStock() {
        var isolated = stock(20, 30, 40, false, false);
        for (int business : List.of(118, 115, 111, 113, 124)) {
            assertThrows(ServiceException.class, () -> transactions.createTransaction(
                    request(2, business, 20, 30, 40).setMaterialStockId(isolated.getId())));
        }
        assertThrows(ServiceException.class, () -> transactions.createTransaction(
                request(3, 111, 20, 30, 40).setMaterialStockId(isolated.getId())));
        assertThrows(ServiceException.class, () -> transactions.createTransaction(
                request(6, 113, 20, 30, 40).setMaterialStockId(isolated.getId())));
        assertQuantity(isolated.getId(), "100");
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM mes_wm_transaction", Integer.class));
        verify(kittingService, never()).validateAndConsumeOutbound(any(), any(), any(), any());
    }

    @Test void qualityHoldCannotBeBypassedEvenIfOrdinaryFrozenFlagIsFalse() {
        var held = stock(2, 3, 4, true, false);
        assertThrows(ServiceException.class, () -> transactions.createTransaction(
                request(2, 118, 2, 3, 4).setMaterialStockId(held.getId())));
        assertThrows(ServiceException.class, () -> stocks.updateMaterialStockFrozen(
                new MesWmMaterialStockFreezeReqVO().setId(held.getId()).setFrozen(false)));
        assertQuantity(held.getId(), "100");
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM mes_wm_transaction", Integer.class));
    }

    @Test void internalWorkflowUnfreezeReleasesNormalFreezesButNeverReleasesHistoricalQualityHold() {
        var good = stock(2, 3, 4, false, true);
        var held = stock(20, 30, 40, true, true);
        stocks.updateMaterialStockFrozen(List.of(good.getId(), held.getId()), false);
        assertFalse(stockMapper.selectById(good.getId()).getFrozen());
        assertTrue(stockMapper.selectById(held.getId()).getFrozen());
        assertTrue(stockMapper.selectById(held.getId()).getQualityHold());
        assertThrows(ServiceException.class, () -> transactions.createTransaction(
                request(2, 118, 20, 30, 40).setMaterialStockId(held.getId())));
    }

    @Test void qualifiedNormalStockRemainsSaleableAndLedgerRecordsOnlyActualOutbound() {
        var good = stock(2, 3, 4, false, false);
        transactions.createTransaction(request(2, 118, 2, 3, 4).setMaterialStockId(good.getId()));
        assertQuantity(good.getId(), "95");
        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM mes_wm_transaction WHERE quantity=-5", Integer.class));
    }

    @Test void downstreamFailureRollsBackStockIncrementAndInsertedLedger() {
        var good = stock(2, 3, 4, false, false);
        doThrow(new IllegalStateException("cost layer failure")).when(costService).recordTransaction(any(), any());
        assertThrows(IllegalStateException.class, () -> transactions.createTransaction(request(1, 119, 2, 3, 4)));
        assertQuantity(good.getId(), "100");
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM mes_wm_transaction", Integer.class));
    }

    @Test void outboundPageExcludesIsolationAndHoldBeforePagination() {
        stock(2, 3, 4, false, false);
        stock(20, 30, 40, false, false);
        var held = stock(2, 3, 4, true, false);
        held.setBatchId(10L); stockMapper.updateById(held);
        var result = stocks.getMaterialStockPage(new MesWmMaterialStockPageReqVO()
                .setQualityHold(false).setQuarantineFilter("exclude"));
        assertEquals(1, result.getTotal());
        assertEquals(2L, result.getList().get(0).getWarehouseId());
        assertFalse(Boolean.TRUE.equals(result.getList().get(0).getQualityHold()));
    }

    @Test void realKittingSqlNeverCountsQuarantineOrHistoricalHoldAsEligibleInventory() {
        var good = stock(2, 3, 4, false, false);
        var isolated = stock(20, 30, 40, false, false);
        var held = stock(2, 3, 4, true, false);
        var candidates = kittingMapper.selectCandidates(List.of(7L), 0L);
        assertFalse(candidates.stream().anyMatch(row -> row.getId().equals(isolated.getId())));
        assertEquals(List.of(good.getId()), candidates.stream().filter(row -> Boolean.TRUE.equals(row.isEligible()))
                .map(cn.iocoder.yudao.module.mes.dal.mysql.pro.kitting.KittingStockRow::getId).toList());
        assertFalse(kittingMapper.selectStock(isolated.getId(), 0L).isEligible());
        assertFalse(kittingMapper.lockStock(held.getId(), 0L).isEligible());
        assertFalse(kittingMapper.lockStock(isolated.getId(), 0L).isEligible());
    }

    private MesWmMaterialStockDO stock(long warehouse, long location, long area, boolean hold, boolean frozen) {
        var stock = MesWmMaterialStockDO.builder().itemId(7L).itemTypeId(1L).batchId(9L).batchCode("B9")
                .warehouseId(warehouse).locationId(location).areaId(area).quantity(new BigDecimal("100"))
                .qualityHold(hold).qualityHoldReason(hold ? "历史FAIL退货混入" : null).frozen(frozen).build();
        stockMapper.insert(stock);
        return stock;
    }

    private MesWmTransactionSaveReqDTO request(int type, int business, long warehouse, long location, long area) {
        return new MesWmTransactionSaveReqDTO().setType(type).setBizType(business).setBizId(1L).setBizCode("Q-TEST")
                .setBizLineId(1L).setItemId(7L).setBatchId(9L).setBatchCode("B9").setWarehouseId(warehouse)
                .setLocationId(location).setAreaId(area).setQuantity(new BigDecimal(type == 1 ? "5" : "-5"));
    }

    private void assertQuantity(long id, String amount) {
        assertEquals(0, new BigDecimal(amount).compareTo(stockMapper.selectById(id).getQuantity()));
    }
}
