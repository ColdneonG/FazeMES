package cn.iocoder.yudao.module.mes.service.wm.returnsales;

import cn.iocoder.yudao.framework.common.exception.ServiceException;
import cn.iocoder.yudao.framework.test.core.ut.BaseDbUnitTest;
import cn.iocoder.yudao.module.mes.dal.dataobject.wm.returnsales.*;
import cn.iocoder.yudao.module.mes.dal.mysql.wm.returnsales.*;
import cn.iocoder.yudao.module.mes.enums.wm.*;
import cn.iocoder.yudao.module.mes.service.md.client.MesMdClientService;
import cn.iocoder.yudao.module.mes.service.md.item.MesMdItemService;
import cn.iocoder.yudao.module.mes.service.wm.transaction.MesWmTransactionService;
import cn.iocoder.yudao.module.mes.service.wm.transaction.dto.MesWmTransactionSaveReqDTO;
import jakarta.annotation.Resource;
import org.junit.jupiter.api.*;
import org.springframework.context.annotation.*;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.annotation.EnableTransactionManagement;
import org.springframework.transaction.support.TransactionTemplate;

import java.math.BigDecimal;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.*;
import static org.mockito.Mockito.*;

/** Real H2 document/line/detail rows and transaction rollback; posting records actual stock and ledger rows. */
@Import({MesWmReturnSalesServiceImpl.class, MesWmReturnSalesQuarantineTest.Transactions.class})
class MesWmReturnSalesQuarantineTest extends BaseDbUnitTest {
    @Configuration(proxyBeanMethods = false)
    @EnableTransactionManagement(proxyTargetClass = true)
    static class Transactions {
        @Bean JdbcTemplate jdbcTemplate(javax.sql.DataSource source) { return new JdbcTemplate(source); }
    }

    @Resource private MesWmReturnSalesService sales;
    @Resource private MesWmReturnSalesMapper headerMapper;
    @Resource private MesWmReturnSalesLineMapper lineMapper;
    @Resource private MesWmReturnSalesDetailMapper detailMapper;
    @Resource private JdbcTemplate jdbc;
    @Resource private PlatformTransactionManager transactionManager;
    @MockitoBean private MesWmReturnSalesLineService lineService;
    @MockitoBean private MesWmReturnSalesDetailService detailService;
    @MockitoBean private MesWmReturnSalesDeliveryService deliveryService;
    @MockitoBean private MesWmReturnSalesSourceService sourceService;
    @MockitoBean private MesMdClientService clientService;
    @MockitoBean private MesMdItemService itemService;
    @MockitoBean private MesWmTransactionService posting;
    @MockitoBean private cn.iocoder.yudao.module.mes.service.wm.warehouse.MesWmWarehouseService warehouseService;

    @BeforeEach void fixture() {
        String base = ",creator VARCHAR(64) DEFAULT '',create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,updater VARCHAR(64) DEFAULT '',update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,deleted BOOLEAN DEFAULT FALSE,tenant_id BIGINT DEFAULT 0";
        jdbc.execute("CREATE TABLE IF NOT EXISTS mes_wm_return_sales(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,code VARCHAR(64),name VARCHAR(64),sales_order_code VARCHAR(64),client_id BIGINT,return_date TIMESTAMP,return_reason VARCHAR(255),status INT,remark VARCHAR(500)" + base + ")");
        jdbc.execute("CREATE TABLE IF NOT EXISTS mes_wm_return_sales_detail(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,return_id BIGINT,line_id BIGINT,item_id BIGINT,quantity DECIMAL(20,6),batch_id BIGINT,batch_code VARCHAR(64),warehouse_id BIGINT,location_id BIGINT,area_id BIGINT,remark VARCHAR(500)" + base + ")");
        jdbc.execute("CREATE TABLE IF NOT EXISTS quarantine_test_stock(warehouse_id BIGINT PRIMARY KEY,quantity DECIMAL(20,6))");
        jdbc.execute("CREATE TABLE IF NOT EXISTS quarantine_test_ledger(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,warehouse_id BIGINT,quantity DECIMAL(20,6))");
        jdbc.update("DELETE FROM mes_wm_return_sales");
        jdbc.update("DELETE FROM mes_wm_return_sales_detail");
        jdbc.update("DELETE FROM quarantine_test_stock");
        jdbc.update("DELETE FROM quarantine_test_ledger");
        jdbc.update("INSERT INTO quarantine_test_stock VALUES(2,100),(20,0)");
        when(warehouseService.validateWarehouseExists(anyLong())).thenAnswer(i ->
                new cn.iocoder.yudao.module.mes.dal.dataobject.wm.warehouse.MesWmWarehouseDO()
                        .setId(i.getArgument(0)).setCode(Long.valueOf(20L).equals(i.getArgument(0))
                                ? "QUALITY_QUARANTINE_WAREHOUSE" : "FG"));
        when(lineService.getReturnSalesLineListByReturnId(anyLong())).thenAnswer(i -> lineMapper.selectListByReturnId(i.getArgument(0)));
        when(sourceService.lockDocumentSources(anyLong())).thenAnswer(i -> lineMapper.selectListByReturnIdForUpdate(i.getArgument(0)));
        when(detailService.getReturnSalesDetailListByReturnId(anyLong())).thenAnswer(i -> detailMapper.selectListByReturnId(i.getArgument(0)));
        doAnswer(i -> {
            for (MesWmTransactionSaveReqDTO row : i.<List<MesWmTransactionSaveReqDTO>>getArgument(0)) {
                jdbc.update("UPDATE quarantine_test_stock SET quantity=quantity+? WHERE warehouse_id=?", row.getQuantity(), row.getWarehouseId());
                jdbc.update("INSERT INTO quarantine_test_ledger(warehouse_id,quantity) VALUES(?,?)", row.getWarehouseId(), row.getQuantity());
            }
            return null;
        }).when(posting).createTransactionList(anyList());
    }

    @Test void rejectedReturnCannotMixWithExistingGoodStockInNormalWarehouse() {
        long id = returned(2, 2);
        assertThrows(ServiceException.class, () -> new TransactionTemplate(transactionManager)
                .executeWithoutResult(status -> sales.stockReturnSales(id)));
        assertEquals(0, new BigDecimal("100").compareTo(jdbc.queryForObject("SELECT quantity FROM quarantine_test_stock WHERE warehouse_id=2", BigDecimal.class)));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM quarantine_test_ledger", Integer.class));
        assertEquals(MesWmReturnSalesStatusEnum.APPROVED.getStatus(), headerMapper.selectById(id).getStatus());
    }

    @Test void rejectedReturnIsQuarantinedWithoutChangingSameBatchGoodStock() {
        long id = returned(2, 20);
        sales.stockReturnSales(id);
        assertQuantity("100", 2);
        assertQuantity("5", 20);
        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM quarantine_test_ledger", Integer.class));
        assertEquals(MesWmReturnSalesStatusEnum.FINISHED.getStatus(), headerMapper.selectById(id).getStatus());
        assertThrows(ServiceException.class, () -> sales.stockReturnSales(id));
        assertQuantity("5", 20);
    }

    @Test void qualifiedReturnCanStillJoinGoodStock() {
        sales.stockReturnSales(returned(1, 2));
        assertQuantity("105", 2);
        assertQuantity("0", 20);
    }

    @Test void pendingOrUnknownQualityCannotBePassedByForgingReadyDocumentStatus() {
        assertThrows(ServiceException.class, () -> sales.stockReturnSales(returned(0, 20)));
        assertThrows(ServiceException.class, () -> sales.stockReturnSales(returned(99, 2)));
        assertQuantity("100", 2);
        assertQuantity("0", 20);
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM quarantine_test_ledger", Integer.class));
    }

    @Test void failedPostingRollsBackStockLedgerAndDocumentState() {
        long id = returned(2, 20);
        doAnswer(i -> {
            jdbc.update("UPDATE quarantine_test_stock SET quantity=quantity+5 WHERE warehouse_id=20");
            jdbc.update("INSERT INTO quarantine_test_ledger(warehouse_id,quantity) VALUES(20,5)");
            throw new IllegalStateException("simulated posting failure");
        }).when(posting).createTransactionList(anyList());
        assertThrows(IllegalStateException.class, () -> sales.stockReturnSales(id));
        assertQuantity("0", 20);
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM quarantine_test_ledger", Integer.class));
        assertEquals(MesWmReturnSalesStatusEnum.APPROVED.getStatus(), headerMapper.selectById(id).getStatus());
    }

    private void assertQuantity(String amount, long warehouse) {
        assertEquals(0, new BigDecimal(amount).compareTo(jdbc.queryForObject(
                "SELECT quantity FROM quarantine_test_stock WHERE warehouse_id=?", BigDecimal.class, warehouse)));
    }

    private long returned(int quality, long warehouse) {
        var header = new MesWmReturnSalesDO().setCode("RET").setName("退货").setClientId(1L)
                .setStatus(MesWmReturnSalesStatusEnum.APPROVED.getStatus());
        headerMapper.insert(header);
        var line = new MesWmReturnSalesLineDO().setReturnId(header.getId()).setItemId(7L)
                .setBatchId(9L).setQuantity(new BigDecimal("5")).setQualityStatus(quality);
        lineMapper.insert(line);
        detailMapper.insert(new MesWmReturnSalesDetailDO().setReturnId(header.getId()).setLineId(line.getId())
                .setItemId(7L).setBatchId(9L).setBatchCode("B9").setQuantity(new BigDecimal("5"))
                .setWarehouseId(warehouse).setLocationId(3L).setAreaId(4L));
        return header.getId();
    }
}
