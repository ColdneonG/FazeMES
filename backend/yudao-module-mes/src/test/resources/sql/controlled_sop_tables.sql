CREATE TABLE IF NOT EXISTS mes_sop_document (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar(64) NOT NULL,
  name varchar(200) NOT NULL,
  item_id bigint NOT NULL,
  process_id bigint NOT NULL,
  creator varchar(64) DEFAULT '', create_time timestamp DEFAULT CURRENT_TIMESTAMP,
  updater varchar(64) DEFAULT '', update_time timestamp DEFAULT CURRENT_TIMESTAMP,
  deleted boolean DEFAULT FALSE, tenant_id bigint DEFAULT 1
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_sop_binding ON mes_sop_document (tenant_id,item_id,process_id);
CREATE TABLE IF NOT EXISTS mes_sop_version (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id bigint NOT NULL,
  version_no varchar(64) NOT NULL,
  title varchar(200) NOT NULL,
  change_note clob NULL,
  status varchar(20) NOT NULL DEFAULT 'DRAFT',
  steps_json clob NOT NULL,
  attachments_json clob NOT NULL,
  model_url varchar(2048) NOT NULL DEFAULT '',
  submitted_by bigint NULL,
  submitted_at datetime NULL,
  reviewed_by bigint NULL,
  reviewed_at datetime NULL,
  review_comment clob NULL,
  published_by bigint NULL,
  published_at datetime NULL,
  disabled_by bigint NULL,
  disabled_at datetime NULL,
  disable_reason clob NULL,
  creator varchar(64) DEFAULT '', create_time timestamp DEFAULT CURRENT_TIMESTAMP,
  updater varchar(64) DEFAULT '', update_time timestamp DEFAULT CURRENT_TIMESTAMP,
  deleted boolean DEFAULT FALSE, tenant_id bigint DEFAULT 1
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_sop_version ON mes_sop_version (tenant_id,document_id,version_no);
CREATE TABLE IF NOT EXISTS mes_sop_task_snapshot (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id bigint NOT NULL,
  item_id bigint NOT NULL,
  process_id bigint NOT NULL,
  document_id bigint NOT NULL,
  version_id bigint NOT NULL,
  version_no varchar(64) NOT NULL,
  title varchar(200) NOT NULL,
  steps_json clob NOT NULL,
  attachments_json clob NOT NULL,
  model_url varchar(2048) NOT NULL DEFAULT '',
  creator varchar(64) DEFAULT '', create_time timestamp DEFAULT CURRENT_TIMESTAMP,
  updater varchar(64) DEFAULT '', update_time timestamp DEFAULT CURRENT_TIMESTAMP,
  deleted boolean DEFAULT FALSE, tenant_id bigint DEFAULT 1
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_sop_task ON mes_sop_task_snapshot (tenant_id,task_id);
CREATE TABLE IF NOT EXISTS mes_sop_step_record (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  snapshot_id bigint NOT NULL,
  step_id varchar(64) NOT NULL,
  viewed_at datetime NOT NULL,
  viewed_by bigint NOT NULL,
  confirmed_at datetime NULL,
  confirmed_by bigint NULL,
  parameters_json clob NULL,
  photos_json clob NULL,
  creator varchar(64) DEFAULT '', create_time timestamp DEFAULT CURRENT_TIMESTAMP,
  updater varchar(64) DEFAULT '', update_time timestamp DEFAULT CURRENT_TIMESTAMP,
  deleted boolean DEFAULT FALSE, tenant_id bigint DEFAULT 1
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_sop_step_record ON mes_sop_step_record (tenant_id,snapshot_id,step_id);
