CREATE TABLE IF NOT EXISTS mes_pro_sn_trace (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sn_id bigint NOT NULL, sn_code varchar(128) NOT NULL,
 work_order_id bigint NOT NULL, product_id bigint NOT NULL, product_batch_code varchar(128), status varchar(20) NOT NULL,
 tenant_id bigint NOT NULL, creator varchar(64) DEFAULT '', updater varchar(64) DEFAULT '',
 create_time timestamp DEFAULT CURRENT_TIMESTAMP, update_time timestamp DEFAULT CURRENT_TIMESTAMP, deleted boolean DEFAULT FALSE,
 UNIQUE(tenant_id,sn_id), UNIQUE(tenant_id,sn_code)
);
CREATE TABLE IF NOT EXISTS mes_pro_sn_station (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, trace_id bigint NOT NULL, request_key varchar(64) NOT NULL,
 request_hash varchar(64) NOT NULL, work_order_id bigint NOT NULL, feedback_id bigint NOT NULL, feedback_code varchar(128),
 task_id bigint NOT NULL, route_id bigint NOT NULL, process_id bigint NOT NULL, process_sort int NOT NULL,
 workstation_id bigint, operator_id bigint NOT NULL, feedback_user_id bigint, station_time timestamp NOT NULL, feedback_time timestamp,
 tenant_id bigint NOT NULL, creator varchar(64) DEFAULT '', updater varchar(64) DEFAULT '',
 create_time timestamp DEFAULT CURRENT_TIMESTAMP, update_time timestamp DEFAULT CURRENT_TIMESTAMP, deleted boolean DEFAULT FALSE,
 UNIQUE(tenant_id,trace_id,request_key), UNIQUE(tenant_id,trace_id,process_id)
);
CREATE TABLE IF NOT EXISTS mes_pro_sn_material (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, trace_id bigint NOT NULL, station_id bigint NOT NULL,
 feedback_id bigint NOT NULL, consume_id bigint NOT NULL, consume_line_id bigint NOT NULL, consume_detail_id bigint NOT NULL,
 material_stock_id bigint NOT NULL, item_id bigint NOT NULL, batch_id bigint, batch_code varchar(128), quantity decimal(24,6) NOT NULL CHECK(quantity > 0),
 tenant_id bigint NOT NULL, creator varchar(64) DEFAULT '', updater varchar(64) DEFAULT '',
 create_time timestamp DEFAULT CURRENT_TIMESTAMP, update_time timestamp DEFAULT CURRENT_TIMESTAMP, deleted boolean DEFAULT FALSE,
 UNIQUE(tenant_id,station_id,consume_detail_id)
);
