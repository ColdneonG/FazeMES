-- Standalone H2 schema; intentionally independent of shared MES test DDL.
CREATE TABLE mes_report_definition (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,latest_version INT DEFAULT 0,published_version INT,
 tenant_id BIGINT,creator VARCHAR(64),updater VARCHAR(64),create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,deleted BOOLEAN DEFAULT FALSE
);
CREATE TABLE mes_report_version (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,report_id BIGINT,version INT,name VARCHAR(100) NOT NULL,config_json CLOB,tenant_id BIGINT,
 creator VARCHAR(64),create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,deleted BOOLEAN DEFAULT FALSE,
 UNIQUE(tenant_id,report_id,version)
);
CREATE TABLE mes_pro_work_order (id BIGINT,code VARCHAR(100),name VARCHAR(100),quantity DECIMAL(18,4),status INT,tenant_id BIGINT,deleted BOOLEAN DEFAULT FALSE,request_date TIMESTAMP,create_time TIMESTAMP);
